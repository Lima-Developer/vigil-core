CREATE TABLE workspace_telemetry_sample (
    observed_at          TEXT PRIMARY KEY NOT NULL,
    window_start         TEXT,
    target_id            TEXT NOT NULL,
    state                TEXT NOT NULL CHECK (state IN ('available','warming_up','error')),
    quality              TEXT NOT NULL CHECK (quality IN ('measured','partial','unknown')),
    calls                INTEGER,
    execution_millis     TEXT,
    mean_execution_millis TEXT,
    rows_count           INTEGER,
    shared_hits          INTEGER,
    shared_reads         INTEGER,
    temp_reads           INTEGER,
    temp_writes          INTEGER,
    active_sessions      INTEGER,
    waiting_sessions     INTEGER,
    blocked_sessions     INTEGER,
    reason               TEXT,
    CHECK ((state = 'available') = (window_start IS NOT NULL)),
    CHECK (calls IS NULL OR calls >= 0),
    CHECK (rows_count IS NULL OR rows_count >= 0),
    CHECK (active_sessions IS NULL OR active_sessions >= 0),
    CHECK (waiting_sessions IS NULL OR waiting_sessions >= 0),
    CHECK (blocked_sessions IS NULL OR blocked_sessions >= 0)
);
